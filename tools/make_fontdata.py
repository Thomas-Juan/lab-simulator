# -*- coding: utf-8 -*-
"""Builds game/fontdata.py: the game's embedded typefaces, so text looks the same on Windows,
macOS and in the browser (where pygame has no system fonts).

    Inter (regular, bold)        all text; taken from Journey of a Zebrafish's subset (SIL OFL 1.1)
    DejaVu Sans (regular, bold)  only for characters Inter's subset lacks (superscripts, Greek, maths)
    DejaVu Sans Mono (reg, bold) DNA sequences and instrument read-outs
DejaVu fonts come from matplotlib's data folder (Bitstream Vera licence, redistributable).
Needs fontTools and matplotlib. Run from the lab-simulator folder: python tools/make_fontdata.py"""
import base64
import io
import os
import shutil
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(HERE, "game")
ZF = os.path.join(HERE, "..", "journey-of-a-zebrafish", "game")
sys.path.insert(0, ZF)
import fontdata as zf  # noqa: E402
import matplotlib  # noqa: E402

TTF = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf")
FALLBACK = "U+00A0-024F,U+0370-03FF,U+2010-2044,U+2070-209F,U+2100-215F,U+2190-21FF,U+2200-22FF,U+2300-23FF,U+25A0-25FF"
MONO = "U+0020-007E,U+00A0-00FF,U+2013-2014,U+2026,U+2190-2193"


def sub(path, unicodes):
    opts = subset.Options()
    opts.layout_features = ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    font = TTFont(path)
    s = subset.Subsetter(opts)
    s.populate(unicodes=subset.parse_unicodes(unicodes))
    s.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def chunks(b):
    t = base64.b64encode(b).decode("ascii")
    return "(\n" + "\n".join('    "%s"' % t[i:i + 96] for i in range(0, len(t), 96)) + "\n)"


inter_r = base64.b64decode("".join(zf.REGULAR))
inter_b = base64.b64decode("".join(zf.BOLD))
cover = sorted(TTFont(io.BytesIO(inter_r)).getBestCmap())
out = ['# -*- coding: utf-8 -*-',
       '"""Embedded typefaces (generated by tools/make_fontdata.py; do not edit by hand).',
       '',
       'Inter 4.1 by Rasmus Andersson, SIL Open Font License 1.1 (see fonts/Inter-LICENSE.txt).',
       'DejaVu Sans and DejaVu Sans Mono, Bitstream Vera licence (see fonts/LICENSE_DEJAVU)."""',
       '',
       'INTER_CODEPOINTS = %r' % (cover,),
       '',
       'REGULAR = ' + chunks(inter_r),
       'BOLD = ' + chunks(inter_b),
       'FALLBACK = ' + chunks(sub(os.path.join(TTF, "DejaVuSans.ttf"), FALLBACK)),
       'FALLBACK_BOLD = ' + chunks(sub(os.path.join(TTF, "DejaVuSans-Bold.ttf"), FALLBACK)),
       'MONO = ' + chunks(sub(os.path.join(TTF, "DejaVuSansMono.ttf"), MONO)),
       'MONO_BOLD = ' + chunks(sub(os.path.join(TTF, "DejaVuSansMono-Bold.ttf"), MONO)),
       '']
open(os.path.join(GAME, "fontdata.py"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
os.makedirs(os.path.join(GAME, "fonts"), exist_ok=True)
shutil.copyfile(os.path.join(ZF, "fonts", "Inter-LICENSE.txt"), os.path.join(GAME, "fonts", "Inter-LICENSE.txt"))
shutil.copyfile(os.path.join(TTF, "LICENSE_DEJAVU"), os.path.join(GAME, "fonts", "LICENSE_DEJAVU"))
print("wrote game/fontdata.py (%d KB)" % (os.path.getsize(os.path.join(GAME, "fontdata.py")) // 1024))
